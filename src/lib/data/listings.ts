export function getListing(id: string) {
  return listings.find((l) => l.id === id);
}

export function getActiveListings() {
  return [...listings]
    .filter((l) => l.status === "active")
    .sort((a, b) => +new Date(b.publishedAt) - +new Date(a.publishedAt));
}

export function getListingsBySpecies(speciesId: string) {
  return getActiveListings().filter((l) => l.speciesId === speciesId);
}

export function getListingsBySeller(sellerId: string) {
  return getActiveListings().filter((l) => l.sellerId === sellerId);
}

export function getListingsByGroup(_groupId: string) {
  return getActiveListings();
}

export function searchListings(query: string) {
  const q = query.toLowerCase().trim();
  if (!q) return getActiveListings();
  return getActiveListings();
}
